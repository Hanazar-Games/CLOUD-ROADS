export function drawSignLetter(letter: string, x: number, y: number, sx: number, sy: number, pixel: (x: number, y: number, coverage: number) => void): void {
  const strokes = paths[letter]; if (!strokes) return;
  const radius = 0.43, feather = 0.65 / Math.min(sx, sy);
  for (let py = Math.floor(y - sy); py <= y + sy * 8; py++) for (let px = Math.floor(x - sx); px <= x + sx * 6; px++) {
    const u = (px + 0.5 - x) / sx, v = (py + 0.5 - y) / sy;
    let distance = Infinity;
    for (const stroke of strokes) for (let i = 0; i < stroke.length - 2; i += 2) {
      const ax = stroke[i], ay = stroke[i + 1], dx = stroke[i + 2] - ax, dy = stroke[i + 3] - ay;
      const t = Math.max(0, Math.min(1, ((u - ax) * dx + (v - ay) * dy) / (dx * dx + dy * dy)));
      distance = Math.min(distance, Math.hypot(u - ax - dx * t, v - ay - dy * t));
    }
    const coverage = Math.max(0, Math.min(1, (radius + feather - distance) / (2 * feather)));
    if (coverage) pixel(px, py, coverage);
  }
}
